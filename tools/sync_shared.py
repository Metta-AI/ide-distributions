"""Copy the shared sources into each distribution that uses them.

Hermes installs a distribution by copying its one folder (``hermes profile install <dir>``),
so code and documents shared by several distributions must sit inside each folder. Edit the
source of truth, run this script, and commit the source and the copies together:

    python3 tools/sync_shared.py

Sources and their copies:

- ``shared/ide_research_core/`` -> ``<distribution>/src/ide_research_core/``
- ``ontology/KNOWLEDGE.md``, ``VOCABULARY.md`` and ``ONTOLOGY.md`` -> the end of ``<distribution>/SOUL.md``, after the line
  ``ONTOLOGY_MARKER`` (Hermes loads SOUL.md in every session, so every turn has the shared
  vocabulary without reading another file). Only the research
  distributions get it: ``play`` uses the package's Softmax tool, not the research vocabulary.
- ``shared/skills/autoresearch/`` -> ``<distribution>/skills/autoresearch/`` for the research
  distributions (the research-method skills both the orchestrator and researchers use)
- ``researcher/games/<game>/skills/`` -> ``<distribution>/skills/<game>/`` for the research
  distributions (a shipped game's binding skills; Hermes loads skills only from ``skills/``)
- ``researcher/games/<game>/`` -> ``orchestrator/games/<game>/`` (the whole shipped game
  folder: contract, docs, tools, baselines and seed. The orchestrator reads the same game
  knowledge as the researchers, runs the game tools, and seeds a game's workspace itself
  with ``game_prepare``), and ``researcher/games/_template/`` likewise
- ``researcher/doctrine/`` -> ``orchestrator/doctrine/`` (the research doctrine, which
  ``research workspace bootstrap`` writes into a new workspace as ``AGENTS.md``)

The orchestrator is meant to have everything a researcher has except the researcher's
restrictions (``plugins/researcher_guard``, the approvals deny list), so new researcher
content belongs in one of these copies.

A distribution takes part when its folder exists. Each copy of the package gets a
``GENERATED.md`` that says where to edit instead. Files in a package copy that no longer
exist in the source are removed, so a copy always equals its source.
"""

import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DISTRIBUTIONS = ("researcher", "orchestrator", "play")
RESEARCH_DISTRIBUTIONS = ("researcher", "orchestrator")  # the ones that embed the ontology
PACKAGE = "ide_research_core"
SKILLS = "autoresearch"  # research method skills, shared by both research profiles
# Local output, never copied: Python caches anywhere, and a game's ``tools/.cache`` and
# ``tools/bin`` (its build output, ``games/<game>/tools/.gitignore``).
SKIPPED = {"__pycache__", ".pytest_cache", ".ruff_cache"}
BUILD_OUTPUT = {("tools", ".cache"), ("tools", "bin")}
MARKER = "GENERATED.md"
# Embedded in order after the marker: built-in knowledge, the Softmax vocabulary (generated by
# tools/refresh_vocabulary.py from metta) and the research ontology.
EMBEDDED = ("KNOWLEDGE.md", "VOCABULARY.md", "ONTOLOGY.md")
ONTOLOGY_MARKER = "<!-- ontology: generated by tools/sync_shared.py from ontology/ONTOLOGY.md; edit there -->"
def marker_text(source: str) -> str:
    return (
        "# Generated copy\n\n"
        f"This folder is a copy of `{source}/` made by `tools/sync_shared.py`.\n"
        "Edit the source, then run the script; changes made here are overwritten.\n"
    )


def skipped(relative: Path) -> bool:
    return bool(SKIPPED.intersection(relative.parts)) or tuple(relative.parts[:2]) in BUILD_OUTPUT


def source_files(source: Path) -> dict[Path, Path]:
    """Relative path -> absolute path of every file to copy."""
    files = {}
    for path in sorted(source.rglob("*")):
        relative = path.relative_to(source)
        if path.is_file() and not skipped(relative):
            files[relative] = path
    return files


def mirror(source: Path, target: Path) -> list[str]:
    marker_wanted = marker_text(source.relative_to(REPO).as_posix())
    """Make ``target`` equal ``source`` plus the marker file; return what changed."""
    wanted = source_files(source)
    changes = []
    for relative, path in wanted.items():
        destination = target / relative
        if destination.is_file() and destination.read_bytes() == path.read_bytes():
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
        changes.append(f"wrote {destination.relative_to(REPO)}")
    marker = target / MARKER
    if not marker.is_file() or marker.read_text() != marker_wanted:
        marker.write_text(marker_wanted)
        changes.append(f"wrote {marker.relative_to(REPO)}")
    for path in sorted(target.rglob("*"), reverse=True):
        relative = path.relative_to(target)
        if skipped(relative):
            continue
        if path.is_file() and relative not in wanted and relative != Path(MARKER):
            path.unlink()
            changes.append(f"removed {path.relative_to(REPO)}")
        elif path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    return changes


def embed_ontology(soul: Path, ontology: Path) -> list[str]:
    """Replace everything after ``ONTOLOGY_MARKER`` in ``soul`` with the ontology."""
    text = soul.read_text(encoding="utf-8")
    head, found, _ = text.partition(ONTOLOGY_MARKER)
    if not found:
        raise SystemExit(f"{soul.relative_to(REPO)} has no ontology marker line: {ONTOLOGY_MARKER}")
    embedded = [ontology.parent / name for name in EMBEDDED]
    wanted = head + ONTOLOGY_MARKER + "\n\n" + "\n".join(p.read_text(encoding="utf-8") for p in embedded)
    if wanted == text:
        return []
    soul.write_text(wanted, encoding="utf-8")
    return [f"wrote {soul.relative_to(REPO)}"]


def main() -> int:
    changes = []
    for name in DISTRIBUTIONS:
        distribution = REPO / name
        if not (distribution / "distribution.yaml").is_file():
            continue
        changes += mirror(REPO / "shared" / PACKAGE, distribution / "src" / PACKAGE)
        if name in RESEARCH_DISTRIBUTIONS:
            changes += mirror(REPO / "shared" / "skills" / SKILLS, distribution / "skills" / SKILLS)
            changes += embed_ontology(distribution / "SOUL.md", REPO / "ontology" / "ONTOLOGY.md")
    orchestrator = REPO / "orchestrator"
    if (orchestrator / "distribution.yaml").is_file():
        # Every shipped game folder, and the template (``research game new`` and the contract).
        for contract in sorted((REPO / "researcher" / "games").glob("*/GAME.md")):
            changes += mirror(contract.parent, orchestrator / "games" / contract.parent.name)
        # The research doctrine, so a workspace the orchestrator seeds gets the same AGENTS.md.
        changes += mirror(REPO / "researcher" / "doctrine", orchestrator / "doctrine")
    # A shipped game's binding skills (games/<game>/skills/<binding>/SKILL.md, named
    # <game>-<binding>) load only from a profile's skills/, so both research profiles get a copy.
    for skills in sorted((REPO / "researcher" / "games").glob("*/skills")):
        game = skills.parent.name
        if game.startswith("_"):
            continue
        for name in RESEARCH_DISTRIBUTIONS:
            if (REPO / name / "distribution.yaml").is_file():
                changes += mirror(skills, REPO / name / "skills" / game)
    print("\n".join(changes) if changes else "copies are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
