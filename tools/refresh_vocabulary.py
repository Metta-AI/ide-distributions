"""Refresh ``ontology/VOCABULARY.md`` from metta's canonical Softmax vocabulary.

The source, metta's ``docs/ai/design/vocabulary.md``, is not on a profile host, so its
entity hierarchy and term table are copied here and embedded in each research SOUL by
``tools/sync_shared.py``. Run after the upstream file changes, then run sync_shared:

    python3 tools/refresh_vocabulary.py ~/coding/metta
    python3 tools/sync_shared.py
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = "docs/ai/design/vocabulary.md"
SECTIONS = ("Entity hierarchy", "The terms (authoritative)")
NOTES = """
Notes for these profiles:

- **Agent** is Softmax's alternative name for a Policy. You are also called an agent; when a
  sentence could mean either, say Policy or PolicyVersion for the thing that competes.
- **Promotion** is the Commissioner moving an entry between Divisions. Our own act of
  submitting a candidate as our Champion is a **champion submission** (`research champion`,
  `champion_submit`), never "promotion".
"""


def section(text: str, title: str) -> str:
    match = re.search(rf"^## {re.escape(title)}\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not match:
        raise SystemExit(f"{SOURCE} has no section '## {title}'")
    return match.group(1).strip()


def main() -> int:
    metta = Path(sys.argv[1] if len(sys.argv) > 1 else "~/coding/metta").expanduser()
    text = (metta / SOURCE).read_text(encoding="utf-8")
    commit = ""
    head = metta / ".git"
    if head.exists():
        import subprocess

        commit = subprocess.run(
            ["git", "-C", str(metta), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
        ).stdout.strip()
    parts = [
        "# Softmax vocabulary",
        "",
        f"<!-- generated by tools/refresh_vocabulary.py from metta {SOURCE}"
        + (f" at {commit}" if commit else "") + "; do not edit by hand -->",
        "",
        "Use these terms; correct names that collide with them.",
        "",
        section(text, SECTIONS[0]),
        "",
        section(text, SECTIONS[1]),
        NOTES,
    ]
    (REPO / "ontology" / "VOCABULARY.md").write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
    print("wrote ontology/VOCABULARY.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
