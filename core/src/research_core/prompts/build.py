"""Assemble each profile's SOUL from the prompt parts (design D.7).

A role's SOUL is its parts in file-name order: ``common/*.md`` merged with ``<role>/*.md`` by
the number that prefixes each file name. Every part starts with a ``<!-- role: ... -->``
marker, which is stripped. Three placeholders are filled on the way: ``{{VOCABULARY}}`` (a
compact rendering of ``vocabulary.md``), ``{{RECORDS}}`` (one paragraph per record kind from
the store registry) and ``{{TOOLS}}`` (one line per tool the role has, with its actions).

:func:`check` reports the problems ``tools/build_prompts.py --check`` fails on: a SOUL over its
word budget, a Records section outside its range, a vocabulary over its budget, an unfilled
placeholder, and any text of one role's part appearing in the other role's SOUL (the leak test).
:func:`manifests` gives each plugin manifest's ``provides_tools`` list.

Stdlib only, like the rest of the base package.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from research_core.store.registry import RECORDS, RecordSpec
from research_core.tools.catalog import ROLES, Role, tools_for

PROMPTS_DIR = Path(__file__).resolve().parent
VOCABULARY_PATH = PROMPTS_DIR / "vocabulary.md"

# Word budgets from the design (D.7 and Appendix H).
BUDGETS: dict[str, int] = {"orchestrator": 2500, "researcher": 2000}
RECORDS_RANGE = (300, 500)
VOCABULARY_BUDGET = 350
RECORDS_TITLE = "Records and how you use them"

HEADER = (
    "<!-- Generated by `python tools/build_prompts.py --write` from "
    "core/src/research_core/prompts/; edit the parts there, not this file. -->"
)
SOUL_PATH = "{role}/SOUL.md"
MANIFEST_PATH = "{role}/plugins/{role}/plugin.yaml"

MARKER = re.compile(r"^<!-- role: (common|orchestrator|researcher) -->\n")
PLACEHOLDER = re.compile(r"\{\{[A-Z_]+\}\}")

# Which tools write each record kind, as ``tool`` or ``tool.action`` (the availability check)
# and the name to print. A role that has none of them sees the fallback (the Orchestrator does
# it); ``ALSO`` names a non-tool writer.
WRITERS: dict[str, tuple[tuple[str, str], ...]] = {
    "goal": (("goal.create", "goal"),),
    "task": (("task", "task"),),
    "version": (("version.create", "version"), ("upload", "upload"), ("submit", "submit")),
    "claim": (("claim.write", "claim"),),
    "experiment": (("experiment.create", "experiment"), ("xp", "xp")),
    "directive": (("directive.add", "directive"),),
    "champion": (("submit", "submit"),),
    "capability": (("workspace.capabilities", "workspace.capabilities"),),
    "intent": (
        ("upload", "upload"),
        ("submit", "submit"),
        ("xp", "xp"),
        ("forum_post", "forum_post"),
        ("wiki_edit", "wiki_edit"),
    ),
    "notice": (("ui.notify", "ui.notify"),),
    "session": (),
    "coworld": (("workspace.coworld_switch", "workspace.coworld_switch"),),
}
ALSO: dict[str, str] = {
    "champion": "the watcher's champion sync",
    "capability": "the watcher's checks",
    "session": "the watcher",
    "notice": "the watcher",
}
FALLBACK_WRITER = "the Orchestrator"
# How records without a display id are keyed.
KEYED: dict[str, str] = {
    "champion": "one per League",
    "capability": "one per capability",
    "session": "one per Hermes Session",
    "coworld": "one per Coworld",
}


@dataclass(frozen=True)
class Part:
    path: Path
    role: str  # common, orchestrator or researcher
    body: str  # the text after the marker

    @property
    def order(self) -> tuple[str, int]:
        # Common parts come first when a role part shares the prefix number.
        return (self.path.name, 0 if self.role == "common" else 1)


def load_parts() -> list[Part]:
    """Every part under ``common/``, ``orchestrator/`` and ``researcher/``, by file name."""
    parts: list[Part] = []
    for folder in ("common", *ROLES):
        for path in sorted((PROMPTS_DIR / folder).glob("*.md")):
            text = path.read_text(encoding="utf-8")
            match = MARKER.match(text)
            if match is None:
                raise ValueError(f"{path} does not start with a '<!-- role: ... -->' marker")
            if match.group(1) != folder:
                raise ValueError(f"{path} is marked {match.group(1)!r} but lives in {folder}/")
            parts.append(Part(path, folder, text[match.end() :].strip()))
    return sorted(parts, key=lambda part: part.order)


def parts_for(role: Role) -> list[Part]:
    return [part for part in load_parts() if part.role in ("common", role)]


def render_part(part: Part, role: Role) -> str:
    """A part's text with the placeholders filled for ``role``."""
    text = part.body
    if "{{VOCABULARY}}" in text:
        text = text.replace("{{VOCABULARY}}", render_vocabulary())
    if "{{RECORDS}}" in text:
        text = text.replace("{{RECORDS}}", render_records(role))
    if "{{TOOLS}}" in text:
        text = text.replace("{{TOOLS}}", render_tools(role))
    return text


def render(role: Role) -> str:
    """The whole SOUL of a role."""
    if role not in ROLES:
        raise ValueError(f"unknown role {role!r}")
    blocks = [HEADER, *(render_part(part, role) for part in parts_for(role))]
    return "\n\n".join(blocks) + "\n"


def word_count(role: Role) -> int:
    return words(render(role))


def words(text: str) -> int:
    return len(text.split())


# --- generated sections -------------------------------------------------------------------


def render_vocabulary() -> str:
    """``vocabulary.md`` compactly: the entity diagram, its sentence, one line per term and
    the alias list. The file's closing notes are not rendered."""
    text = VOCABULARY_PATH.read_text(encoding="utf-8")
    diagram = re.search(r"```\n(.*?)```", text, re.DOTALL)
    if diagram is None:
        raise ValueError(f"{VOCABULARY_PATH} has no entity diagram code block")
    after = text[diagram.end() :]
    paragraphs = [p.strip() for p in re.split(r"\n\s*\n", after) if p.strip()]
    sentence = next(p for p in paragraphs if not p.startswith("|"))
    aliases = next(p for p in paragraphs if p.startswith("**Don't use**"))
    terms = []
    for line in after.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) >= 2 and cells[0].startswith("**"):
            meaning = cells[1].rstrip(".")
            terms.append(f"- {cells[0]}: {meaning}.")
    if not terms:
        raise ValueError(f"{VOCABULARY_PATH} has no term table")
    return "\n\n".join(
        ["```\n" + diagram.group(1).rstrip() + "\n```", sentence, "\n".join(terms), aliases]
    )


def render_records(role: Role) -> str:
    """One paragraph per record kind: what it is, its statuses and who writes it."""
    return "\n\n".join(_record_paragraph(spec, role) for spec in RECORDS.values())


def _record_paragraph(spec: RecordSpec, role: Role) -> str:
    key = f"{spec.prefix}-n" if spec.prefix else KEYED[spec.name]
    sentences = [f"**{spec.name.capitalize()}** ({key}). {spec.description}"]
    status = spec.status_field
    if status is not None and spec.statuses:
        label = "States" if status.name == "state" else "Statuses"
        sentences.append(f"{label}: {', '.join(spec.statuses)}.")
    sentences.append(f"Written by {_writers_phrase(spec.name, role)}.")
    return " ".join(sentences)


def _writers_phrase(kind: str, role: Role) -> str:
    names = [f"`{shown}`" for ref, shown in WRITERS[kind] if tool_available(role, ref)]
    if WRITERS[kind] and not names:
        names = [FALLBACK_WRITER]
    if kind in ALSO:
        names.append(ALSO[kind])
    if len(names) == 1:
        return names[0]
    return ", ".join(names[:-1]) + " and " + names[-1]


def tool_available(role: Role, ref: str) -> bool:
    """Whether ``tool`` or ``tool.action`` exists in the role's catalog."""
    tool_name, _, action = ref.partition(".")
    for spec in tools_for(role):
        if spec.name != tool_name:
            continue
        if not action:
            return True
        return any(a.name == action for a in spec.actions_for(role))
    return False


def render_tools(role: Role) -> str:
    """One line per tool the role has: its actions, or its inputs when it has none."""
    lines = []
    for spec in tools_for(role):
        if spec.actions is not None:
            names = ", ".join(action.name for action in spec.actions_for(role))
            lines.append(f"- `{spec.name}`: {names}")
        else:
            lines.append(f"- `{spec.name}` (inputs: {', '.join(spec.params) or 'none'})")
    return "\n".join(lines)


# --- checks -------------------------------------------------------------------------------


def sections(text: str) -> list[tuple[str, str]]:
    """``(title, body)`` for every ``## `` section of a rendered SOUL, in order."""
    found: list[tuple[str, str]] = []
    title, body = "", []
    for line in text.splitlines():
        if line.startswith("## "):
            if title:
                found.append((title, "\n".join(body).strip()))
            title, body = line[3:].strip(), []
        elif title:
            body.append(line)
    if title:
        found.append((title, "\n".join(body).strip()))
    return found


def records_words(role: Role) -> int:
    for title, body in sections(render(role)):
        if title == RECORDS_TITLE:
            return words(body)
    return 0


def check(role: Role) -> list[str]:
    """Every problem with a role's SOUL; empty when it is fit to ship."""
    problems: list[str] = []
    text = render(role)
    count = words(text)
    if count > BUDGETS[role]:
        problems.append(f"{role}: {count} words, over the budget of {BUDGETS[role]}")
    low, high = RECORDS_RANGE
    recorded = records_words(role)
    if not low <= recorded <= high:
        problems.append(f"{role}: the Records section is {recorded} words, outside {low}-{high}")
    vocabulary = words(render_vocabulary())
    if vocabulary > VOCABULARY_BUDGET:
        problems.append(f"{role}: the vocabulary is {vocabulary} words, over {VOCABULARY_BUDGET}")
    for match in PLACEHOLDER.finditer(text):
        problems.append(f"{role}: placeholder {match.group(0)} was not filled")
    if "<!-- role:" in text:
        problems.append(f"{role}: a part's role marker was rendered")
    for other in ROLES:
        if other == role:
            continue
        for part in load_parts():
            if part.role == other and render_part(part, other) in text:
                problems.append(f"{role}: {part.path.parent.name}/{part.path.name} leaks in")
    return problems


def manifests() -> dict[str, list[str]]:
    """Each role's ``provides_tools`` list: the catalog's tool names for that role."""
    return {role: [spec.name for spec in tools_for(role)] for role in ROLES}


PROVIDES_TOOLS = re.compile(r"^provides_tools:.*\n(?:[ \t]+-[^\n]*\n)*", re.MULTILINE)


def set_provides_tools(manifest_text: str, names: list[str]) -> str:
    """``plugin.yaml`` with its ``provides_tools`` list replaced; everything else is kept."""
    if names:
        block = "provides_tools:\n" + "".join(f"  - {name}\n" for name in names)
    else:
        block = "provides_tools: []\n"
    new_text, replaced = PROVIDES_TOOLS.subn(block, manifest_text, count=1)
    if replaced != 1:
        raise ValueError("the manifest has no 'provides_tools:' key to rewrite")
    return new_text
